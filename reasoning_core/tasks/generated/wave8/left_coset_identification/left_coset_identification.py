def _parse_answer(answer):
    if not isinstance(answer, str):
        return None
    try:
        val = ast.literal_eval(answer.strip())
    except Exception:
        return None
    if not isinstance(val, list):
        return None
    return val


class LeftCosetConfig(Config):
    n_group: int = 4
    max_order: int = 4

    def apply_difficulty(self, level):
        self.n_group = sround(self.n_group + level)
        self.max_order = sround(self.max_order + level)


class LeftCosetIdentification(Task):
    summary = ("Given a finite cyclic group as integers mod n, a subgroup generated by an "
               "element, and a specific group element, output the canonical sorted left coset "
               "(list of residues) of the subgroup containing that element.")
    config_cls = LeftCosetConfig

    def generate_entry(self):
        cfg = self.config
        n = cfg.n_group
        if n < 4:
            n = 4
        if n % 2 == 1:
            n = n + 1
        candidates = [k for k in range(1, n) if k != 0]
        attempts = 0
        while True:
            attempts += 1
            if attempts > 200:
                raise RuntimeError("could not build instance")
            a = random.choice(candidates)
            subgroup = sorted({(k * a) % n for k in range(n)})
            order = len(subgroup)
            if order == n:
                continue
            if order > cfg.max_order:
                continue
            g = random.randrange(n)
            coset = sorted({(s + g) % n for s in subgroup})
            if len(coset) != order:
                continue
            break
        subgroup_str = ", ".join(str(x) for x in subgroup)
        answer = json_list(coset)
        metadata = edict({
            "n": int(n),
            "a": int(a),
            "g": int(g),
            "subgroup": subgroup,
            "coset": coset,
        })
        metadata.payload = {
            "n": int(n),
            "generator": int(a),
            "element": int(g),
            "subgroup": subgroup_str,
        }
        return Entry(metadata=metadata, answer=answer)

    def render_prompt(self, metadata):
        p = metadata.payload
        return (
            f"Consider the cyclic group G = Z/{p['n']}Z, the integers mod {p['n']} under "
            f"addition. Let H be the subgroup of G generated by the element {p['generator']}, so "
            f"H = {{ {p['subgroup']} }}. "
            f"The left coset of H containing the element {p['element']} is g + H = "
            f"{{ h + {p['element']} mod {p['n']} : h in H }}. "
            f"List this left coset as a Python list of its elements in increasing sorted "
            f"order over the residues 0..{p['n'] - 1}. "
            f"The answer is that sorted list."
        )

    def score_answer(self, answer, entry):
        val = _parse_answer(answer)
        if val is None:
            return 0.0
        gold = entry.answer
        try:
            gold_val = ast.literal_eval(gold)
        except Exception:
            return 0.0
        if len(val) != len(gold_val):
            return 0.0
        if val == gold_val:
            return 1.0
        return 0.0


def json_list(items):
    return "[" + ", ".join(str(int(x)) for x in items) + "]"
