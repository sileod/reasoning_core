from dataclasses import dataclass, field
import random
from math import gcd

from reasoning_core.template import Task, Entry, Config, edict, render_payload, stochastic_rounding as sround


@dataclass
class GeneratedSubgroupMembershipConfig(Config):
    n_bits: int = 5
    min_order: int = 5

    def apply_difficulty(self, level):
        self.n_bits = sround(self.n_bits + level)
        self.min_order = sround(self.min_order + level)


def _min_exponent(n, a, g):
    d = gcd(a, n)
    order = n // d
    gd = g // d
    ad = a // d
    _mod = order
    inv = pow(ad, -1, _mod)
    e = (gd * inv) % _mod
    if e == 0:
        e = _mod
    return e, order


def _build_instance(n_bits, min_order):
    for _ in range(2000):
        n = random.randint(2 ** (n_bits - 1), 2 ** n_bits - 1)
        a = random.randint(1, n - 1)
        d = gcd(a, n)
        order = n // d
        if order < min_order:
            continue
        k = random.randint(1, order - 1)
        g = (k * a) % n
        if g == 0:
            continue
        e, _ord = _min_exponent(n, a, g)
        if e != k:
            continue
        if not (1 <= e <= _ord - 1):
            continue
        if (e * a) % n != g:
            continue
        if g % d != 0:
            continue
        return n, a, g, e, d, order
    raise RuntimeError("could not build a valid instance")


class GeneratedSubgroupMembership(Task):
    summary = ("Membership in the cyclic subgroup of Z_n generated by an element a: "
               "given n, a, and g, decide containment and provide the minimal positive "
               "exponent witness e with e*a ≡ g (mod n), over varied orders and gaps gcd(a,n).")
    config_cls = GeneratedSubgroupMembershipConfig

    def generate_entry(self):
        cfg = self.config
        n, a, g, e, d, order = _build_instance(cfg.n_bits, cfg.min_order)
        metadata = edict({
            "n": n,
            "a": a,
            "g": g,
            "order": order,
            "gcd": d,
            "answer": int(e),
        })
        metadata.payload = {"n": n, "a": a, "g": g}
        return Entry(metadata=metadata, answer=str(e))

    def render_prompt(self, metadata):
        p = metadata.payload
        return (
            f"Work in the additive cyclic group Z_{p['n']} (elements 0..{p['n'] - 1}, sum modulo {p['n']}). "
            f"Consider the subgroup generated by a = {p['a']}, that is all multiples of {p['a']} modulo {p['n']}. "
            f"The integer g = {p['g']} lies in this generated subgroup. "
            f"The answer is the smallest positive integer e such that e*a ≡ g (mod {p['n']}), written as a plain decimal integer."
        )

    def score_answer(self, answer, entry):
        try:
            val = int(str(answer).strip())
        except (TypeError, ValueError):
            return 0.0
        return 1.0 if val == int(entry.answer) else 0.0


